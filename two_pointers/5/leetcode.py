class Solution:
    def longestPalindrome(self, s: str) -> str:
        if not s:
            return ""

        start = 0
        best = 1

        def expand(left: int, right: int) -> None:
            nonlocal start, best

            while left >= 0 and right < len(s) and s[right] == s[left]:
                if right - left + 1 > best:
                    start = left
                    best = right - left + 1
                left -= 1
                right += 1

        for i in range(len(s)):
            expand(i, i)  # нечетный центр
            expand(i, i + 1)  # четный центр

        return s[start : start + best]


#  Для каждого индекса i проверяются оба вида центра.

# expand(i, i) — центр на букве s[i]. Сначала левая и правая границы стоят на ней самой, это палиндром длины 1. Потом границы шагают наружу: i-1 и i+1, затем i-2 и i+2, и так далее, пока буквы равны и мы не вышли за строку.
# expand(i, i + 1) — центр между s[i] и s[i+1]. Если эти две буквы разные, цикл сразу не выполняется. Если одинаковые, границы так же расходятся в стороны.
# best хранит длину лучшего куска, start — его начало. Как только найденный отрезок длиннее, оба значения обновляются. В конце возвращается срез s[start:start + best].

# На "babad":

# центр 0 (b) даёт "b";
# центр 1 (a) расходится в "bab" — длина 3;
# центр 2 (b) расходится в "aba" — тоже 3, короче текущего не становится, поэтому ответ остаётся "bab";
# чётные центры здесь ничего длиннее не дают.
# На "cbbd" выигрывает чётный центр между двумя b: границы стоят на индексах 1 и 2, буквы равны, длина 2. Дальше c и b не совпадают, расширение останавливается. Ответ — "bb".

# Центров около 2n, из каждого в худшем случае расходимся на всю строку, поэтому время O(n²), дополнительная память O(1). Если подходящих ответов несколько одной длины, вернётся тот, который встретился раньше. Для "babad" это "bab", и "aba" тоже считается верным.
